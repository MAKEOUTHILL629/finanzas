ALTER TABLE "Tarjetas"
  ADD COLUMN IF NOT EXISTS es_titular_externo boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS titular_persona_id int8 REFERENCES "Personas"(id);

CREATE TABLE IF NOT EXISTS "AportesColaborativosCuota" (
  id                    int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuota_detalle_id      int8 NOT NULL REFERENCES "CuotasDetalle"(id) ON DELETE CASCADE,
  compra_credito_id     int8 NOT NULL REFERENCES "ComprasCredito"(id) ON DELETE CASCADE,
  aportante_persona_id  int8 NOT NULL REFERENCES "Personas"(id),
  monto_aportado        numeric(15,2) NOT NULL CHECK (monto_aportado > 0),
  fecha_aporte          date NOT NULL DEFAULT CURRENT_DATE,
  modalidad_entrega     varchar(30) NOT NULL DEFAULT 'TRANSFERIDO_A_MI'
                        CHECK (modalidad_entrega IN ('TRANSFERIDO_A_MI','PAGADO_DIRECTO_AL_TITULAR','PAGO_PROPIO_AL_TITULAR')),
  transaccion_id        int8 REFERENCES "Transacciones"(id) ON DELETE SET NULL,
  comprobante_url       text,
  observaciones         text,
  created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_aportes_cuota ON "AportesColaborativosCuota" (cuota_detalle_id);
CREATE INDEX IF NOT EXISTS idx_aportes_compra ON "AportesColaborativosCuota" (compra_credito_id);

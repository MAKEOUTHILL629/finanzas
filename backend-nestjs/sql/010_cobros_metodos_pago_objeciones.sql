-- =============================================================================
-- 010 · Link compartido de cobro, fase 6 del plan V2: medios de pago, observaciones y abonos parciales
-- Solo DDL ADITIVO e IDEMPOTENTE (CREATE TABLE IF NOT EXISTS / ADD COLUMN IF NOT EXISTS): no cambia ninguna fila existente.
--
--  A. `MetodosPagoUsuario`: dónde puede pagarte cada persona (cuenta de ahorros, Nequi, Daviplata, llave Bre-B…). El enlace
--     público los muestra con un botón «Copiar» por método.
--  B. `ObjecionesCobro`: la persona objeta un cobro (o el total) desde su enlace con un comentario obligatorio; el propietario
--     la resuelve (mantiene, ajusta, excluye o descuenta). Un ajuste NO toca las compras ni los préstamos de origen: se registra como
--     un asiento `AJUSTE_DESCUENTO` en el sub-ledger (columna `tipo_movimiento` libre, sin CHECK) que baja lo que la persona debe.
--  C. `ReportesPagoPersona.saldo_al_reportar`: lo que la persona debía cuando avisó su pago, para distinguir un abono parcial.
-- Reversa manual: `rollback_010.sql`.
-- =============================================================================

-- ─── A. Medios de pago del propietario ───
CREATE TABLE IF NOT EXISTS "MetodosPagoUsuario" (
  id             int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id  int8 NOT NULL REFERENCES "Users"(id),
  tipo           varchar(20) NOT NULL CHECK (tipo IN ('CUENTA_AHORROS', 'CUENTA_CORRIENTE', 'NEQUI', 'DAVIPLATA', 'LLAVE', 'OTRO')),
  entidad        varchar(80) NOT NULL,
  numero         varchar(60) NOT NULL,
  titular        varchar(120),
  documento      varchar(30),
  instrucciones  varchar(500),
  cuenta_id      int8 REFERENCES "CuentasFinancieras"(id) ON DELETE SET NULL,
  qr             bytea,
  qr_tipo        varchar(40),
  qr_tamano      int4,
  activo         boolean NOT NULL DEFAULT true,
  orden          int4 NOT NULL DEFAULT 0,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_metodos_pago_owner ON "MetodosPagoUsuario" (owner_user_id, activo, orden);
CREATE INDEX IF NOT EXISTS idx_metodos_pago_cuenta ON "MetodosPagoUsuario" (cuenta_id) WHERE cuenta_id IS NOT NULL;

-- ─── B. Observaciones de la persona sobre su cobro ───
CREATE TABLE IF NOT EXISTS "ObjecionesCobro" (
  id               int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id    int8 NOT NULL REFERENCES "Users"(id),
  enlace_id        int8 NOT NULL REFERENCES "EnlacesCobroPersona"(id) ON DELETE CASCADE,
  persona_id       int8 NOT NULL REFERENCES "Personas"(id),
  periodo          char(7) NOT NULL,
  alcance          varchar(5) NOT NULL CHECK (alcance IN ('ITEM', 'TOTAL')),
  item_clave       varchar(40),
  item_concepto    varchar(255),
  item_monto       numeric(15,2),
  comentario       varchar(1000) NOT NULL,
  monto_propuesto  numeric(15,2) CHECK (monto_propuesto IS NULL OR monto_propuesto >= 0),
  estado           varchar(10) NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'RESUELTA')),
  resolucion       varchar(12) CHECK (resolucion IS NULL OR resolucion IN ('MANTENIDA', 'AJUSTADA', 'EXCLUIDA', 'DESCUENTO')),
  respuesta        varchar(1000),
  monto_ajuste     numeric(15,2) CHECK (monto_ajuste IS NULL OR monto_ajuste > 0),
  movimiento_id    int8 REFERENCES "MovimientosDeudaPersona"(id) ON DELETE SET NULL,
  resuelta_at      timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CHECK (alcance = 'ITEM' OR item_clave IS NULL)
);
CREATE INDEX IF NOT EXISTS idx_objeciones_owner_estado ON "ObjecionesCobro" (owner_user_id, estado, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_objeciones_enlace ON "ObjecionesCobro" (enlace_id);
CREATE INDEX IF NOT EXISTS idx_objeciones_persona ON "ObjecionesCobro" (persona_id);
CREATE INDEX IF NOT EXISTS idx_objeciones_movimiento ON "ObjecionesCobro" (movimiento_id) WHERE movimiento_id IS NOT NULL;

-- ─── C. Abono parcial ───
ALTER TABLE "ReportesPagoPersona"
  ADD COLUMN IF NOT EXISTS saldo_al_reportar numeric(15,2);

-- Para encontrar rápido los descuentos de una persona en un periodo (lectura de la liquidación y reversa del ajuste).
CREATE INDEX IF NOT EXISTS idx_mov_deuda_ajuste_cobro
  ON "MovimientosDeudaPersona" (owner_user_id, persona_id, periodo_imputacion)
  WHERE tipo_movimiento = 'AJUSTE_DESCUENTO';

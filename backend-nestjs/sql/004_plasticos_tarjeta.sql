-- =============================================================================
-- 004 · Plásticos de una tarjeta de crédito (reposiciones/renovaciones) y plástico de cada compra
-- =============================================================================
-- IDEMPOTENTE. Solo DDL aditivo + relleno de objetos NUEVOS a partir de datos que ya existen: no borra ni reescribe ninguna
-- fila ni columna previa. Se aplica después de 003 con `node scripts/aplicar-sql.js`.
--
--  · `Tarjetas` sigue siendo la LÍNEA DE CRÉDITO (cupo, corte, tasas, historial de compras). Cada vez que el banco reexpide la
--    tarjeta (vencimiento, pérdida, robo, deterioro) se registra un PLÁSTICO nuevo en `TarjetaPlasticos`: el anterior queda
--    archivado (`es_activo = false`, con su fecha de cierre) y todas las compras y cuotas pendientes siguen colgando de la misma línea.
--  · `ComprasCredito.plastico_id` guarda con qué plástico se hizo la compra, cuando se sabe (correo del banco o elección del
--    usuario). Las compras antiguas quedan en NULL: la API deduce el plástico por fecha y lo marca como «inferido».
--  · `Tarjetas.ultimos_4_digitos` se conserva (lista separada por comas de TODOS los plásticos): el parser de correos la sigue usando.
-- =============================================================================

CREATE TABLE IF NOT EXISTS "TarjetaPlasticos" (
  id                int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarjeta_id        int8 NOT NULL REFERENCES "Tarjetas"(id) ON DELETE CASCADE,
  owner_user_id     int8 REFERENCES "Users"(id),
  ultimos_4         varchar(4) NOT NULL CHECK (ultimos_4 ~ '^[0-9]{4}$'),
  es_activo         boolean NOT NULL DEFAULT true,
  vigente_desde     date,
  vigente_hasta     date,
  motivo_reemplazo  varchar(20) CHECK (motivo_reemplazo IS NULL OR motivo_reemplazo IN ('VENCIMIENTO', 'PERDIDA', 'ROBO', 'DETERIORO', 'FRAUDE', 'CAMBIO_PRODUCTO', 'OTRO')),
  reemplaza_a_id    int8 REFERENCES "TarjetaPlasticos"(id) ON DELETE SET NULL,
  notas             text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tarjeta_id, ultimos_4),
  CHECK (vigente_desde IS NULL OR vigente_hasta IS NULL OR vigente_desde <= vigente_hasta)
);

-- A lo sumo UN plástico activo por tarjeta.
CREATE UNIQUE INDEX IF NOT EXISTS ux_tarjeta_plasticos_activo ON "TarjetaPlasticos" (tarjeta_id) WHERE es_activo;
CREATE INDEX IF NOT EXISTS idx_tarjeta_plasticos_owner_u4 ON "TarjetaPlasticos" (owner_user_id, ultimos_4);

ALTER TABLE "ComprasCredito"
  ADD COLUMN IF NOT EXISTS plastico_id int8 REFERENCES "TarjetaPlasticos"(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_compras_credito_plastico ON "ComprasCredito" (plastico_id) WHERE plastico_id IS NOT NULL;

-- ─── Relleno: un plástico por cada grupo de 4 dígitos que ya estaba en Tarjetas.ultimos_4_digitos ───
-- Solo para tarjetas que todavía no tienen plásticos (re-ejecutarlo no duplica nada). El activo es el que tiene el último aviso
-- del banco (o, sin evidencia, el último de la lista). Las fechas se deducen de los correos (primer y último aviso) y solo se
-- escriben cuando hay varios plásticos y evidencia para ese plástico; el más antiguo queda con inicio desconocido (NULL).
DO $$
DECLARE
  t record;
  p record;
  v_cadena int8;
  v_prev int8;
BEGIN
  FOR t IN
    SELECT id, owner_user_id, ultimos_4_digitos
    FROM "Tarjetas" tj
    WHERE tj.ultimos_4_digitos ~ '[0-9]{4}'
      AND NOT EXISTS (SELECT 1 FROM "TarjetaPlasticos" x WHERE x.tarjeta_id = tj.id)
  LOOP
    v_prev := NULL;
    -- Un grupo por plástico, del más antiguo al más reciente según los avisos del banco; sin evidencia, el orden de la lista.
    FOR p IN
      WITH grupos AS (
        SELECT m[1] AS u4, ord
        FROM regexp_matches(t.ultimos_4_digitos, '(?<![0-9])([0-9]{4})(?![0-9])', 'g') WITH ORDINALITY AS r(m, ord)
      ),
      dedup AS (SELECT u4, min(ord) AS ord FROM grupos GROUP BY u4),
      evidencia AS (
        SELECT n.ultimos_4 AS u4,
               min((n.fecha_correo AT TIME ZONE 'America/Bogota')::date) AS primera,
               max((n.fecha_correo AT TIME ZONE 'America/Bogota')::date) AS ultima
        FROM "NotificacionesCorreo" n
        WHERE n.owner_user_id IS NOT DISTINCT FROM t.owner_user_id AND n.ultimos_4 IS NOT NULL
        GROUP BY n.ultimos_4
      )
      SELECT d.u4, d.ord, e.primera, e.ultima,
             count(*) OVER () AS total,
             (d.u4 = first_value(d.u4) OVER (ORDER BY e.ultima DESC NULLS LAST, d.ord DESC)) AS es_el_ultimo
      FROM dedup d LEFT JOIN evidencia e ON e.u4 = d.u4
      ORDER BY e.primera ASC NULLS FIRST, d.ord ASC
    LOOP
      INSERT INTO "TarjetaPlasticos" (tarjeta_id, owner_user_id, ultimos_4, es_activo, vigente_desde, vigente_hasta, reemplaza_a_id, notas)
      VALUES (
        t.id, t.owner_user_id, p.u4, p.es_el_ultimo,
        CASE WHEN p.total > 1 AND v_prev IS NOT NULL AND p.primera IS NOT NULL THEN p.primera END,
        CASE WHEN p.total > 1 AND NOT p.es_el_ultimo AND p.ultima IS NOT NULL THEN p.ultima END,
        v_prev,
        CASE WHEN p.total > 1 AND p.primera IS NOT NULL THEN 'Fechas deducidas de los avisos del banco (primer y último correo con estos dígitos).' END
      )
      RETURNING id INTO v_cadena;
      v_prev := v_cadena;
    END LOOP;
  END LOOP;
END $$;

-- El plástico de las compras que ya nacieron de un correo (se conoce por los 4 dígitos del aviso). Solo toca compras sin plástico.
UPDATE "ComprasCredito" c
   SET plastico_id = p.id
  FROM "NotificacionesCorreo" n
  JOIN "TarjetaPlasticos" p ON p.ultimos_4 = n.ultimos_4
 WHERE n.compra_credito_generada_id = c.id
   AND c.plastico_id IS NULL
   AND p.tarjeta_id = c.tarjeta
   AND n.ultimos_4 IS NOT NULL;

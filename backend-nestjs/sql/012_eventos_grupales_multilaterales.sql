CREATE TABLE IF NOT EXISTS "EventosLiquidacionGrupal" (
  id            int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id int8 NOT NULL REFERENCES "Users"(id),
  nombre        varchar(200) NOT NULL,
  fecha_inicio  date,
  fecha_fin     date,
  estado        varchar(20) NOT NULL DEFAULT 'ABIERTO' CHECK (estado IN ('ABIERTO','CERRADO')),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS "ParticipantesEventoGrupal" (
  id                  int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id           int8 NOT NULL REFERENCES "EventosLiquidacionGrupal"(id) ON DELETE CASCADE,
  persona_id          int8 NOT NULL REFERENCES "Personas"(id),
  alias_bloque        varchar(120),
  peso_participacion  numeric(8,3) NOT NULL DEFAULT 1.0 CHECK (peso_participacion > 0),
  UNIQUE (evento_id, persona_id)
);

CREATE TABLE IF NOT EXISTS "GastosEventoGrupal" (
  id                        int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id                 int8 NOT NULL REFERENCES "EventosLiquidacionGrupal"(id) ON DELETE CASCADE,
  descripcion               varchar(255) NOT NULL,
  monto_total               numeric(15,2) NOT NULL CHECK (monto_total > 0),
  pagado_por_participante_id int8 NOT NULL REFERENCES "ParticipantesEventoGrupal"(id),
  tipo_division             varchar(20) NOT NULL DEFAULT 'PARTES_IGUALES' CHECK (tipo_division IN ('PARTES_IGUALES','PESOS_CUPOS','MONTOS_EXACTOS')),
  division_json             jsonb,
  fecha                     date,
  created_at                timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_eventos_owner ON "EventosLiquidacionGrupal" (owner_user_id, estado);
CREATE INDEX IF NOT EXISTS idx_participantes_evento ON "ParticipantesEventoGrupal" (evento_id);
CREATE INDEX IF NOT EXISTS idx_gastos_evento ON "GastosEventoGrupal" (evento_id);

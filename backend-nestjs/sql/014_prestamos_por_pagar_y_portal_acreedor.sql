ALTER TABLE "Prestamos"
  ADD COLUMN IF NOT EXISTS fecha_compromiso_pago date,
  ADD COLUMN IF NOT EXISTS cuenta_destino_tercero varchar(150),
  ADD COLUMN IF NOT EXISTS token_consulta_publica varchar(64) UNIQUE;

CREATE TABLE IF NOT EXISTS "AbonosPrestamoPasivo" (
  id                    int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prestamo_id           int8 NOT NULL REFERENCES "Prestamos"(id) ON DELETE CASCADE,
  owner_user_id         int8 NOT NULL REFERENCES "Users"(id),
  monto                 numeric(15,2) NOT NULL CHECK (monto > 0),
  fecha_hora_pago       timestamptz NOT NULL DEFAULT now(),
  cuenta_origen_id      int8 REFERENCES "CuentasFinancieras"(id) ON DELETE SET NULL,
  cuenta_destino_detalle varchar(150),
  comprobante           bytea,
  comprobante_nombre    varchar(255),
  comprobante_tipo      varchar(40),
  comprobante_tamano    int4,
  comprobante_url       text,
  transaccion_id        int8 REFERENCES "Transacciones"(id) ON DELETE SET NULL,
  observaciones         text,
  created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_abonos_prestamo_pasivo ON "AbonosPrestamoPasivo" (prestamo_id, fecha_hora_pago DESC);

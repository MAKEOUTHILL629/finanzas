-- =============================================================================
-- 003 · Correos inteligentes (productos por últimos 4 dígitos, vínculos y deduplicación) y cobros a personas
-- =============================================================================
-- IDEMPOTENTE. Solo DDL aditivo + rellenado de columnas NUEVAS derivadas de datos que ya existen:
-- no borra ni reescribe ninguna fila ni columna previa. Se aplica después de 002 con `node scripts/aplicar-sql.js`.
--
--  A. Productos: `Tarjetas.ultimos_4_digitos` (varios valores: "1927,9587" cuando el banco reexpide la tarjeta) y
--     `CuentasFinancieras.es_principal` (cuenta que recibe los avisos del banco que no traen número, p. ej. la nómina).
--  B. `NotificacionesCorreo`: columnas indexables (últimos 4, comercio normalizado, monto, moneda) y los vínculos con
--     lo que se generó o encontró: tarjeta, cuenta, persona, y si la compra/transacción fue CREADA, ya EXISTÍA o es un
--     correo DUPLICADO de otro (evita registrar dos veces el mismo gasto).
--  C. Cobros puntuales (recibo de la luz, mercado, una fiesta…): `CobrosPuntuales` + `CobrosPuntualesPersonas`; cada
--     participante genera un cargo `CARGO_COBRO_PUNTUAL` en el sub-ledger (`MovimientosDeudaPersona.cobro_puntual_id`).
--  D. Enlaces para compartir la liquidación con cada persona (`EnlacesCobroPersona`) y los pagos que esa persona
--     reporta con su comprobante (`ReportesPagoPersona`), que el dueño aprueba o rechaza.
-- =============================================================================

-- ─── A. Productos ───
ALTER TABLE "Tarjetas"
  ADD COLUMN IF NOT EXISTS ultimos_4_digitos varchar;

ALTER TABLE "CuentasFinancieras"
  ADD COLUMN IF NOT EXISTS es_principal boolean NOT NULL DEFAULT false;

-- A lo sumo UNA cuenta principal por usuario.
CREATE UNIQUE INDEX IF NOT EXISTS ux_cuentas_financieras_principal
  ON "CuentasFinancieras" (owner_user_id) WHERE es_principal;

-- ─── B. Notificaciones de correo ───
ALTER TABLE "NotificacionesCorreo"
  ADD COLUMN IF NOT EXISTS ultimos_4 varchar(4),
  ADD COLUMN IF NOT EXISTS comercio_normalizado varchar,
  ADD COLUMN IF NOT EXISTS monto_original numeric(18,4),
  ADD COLUMN IF NOT EXISTS moneda char(3),
  ADD COLUMN IF NOT EXISTS tarjeta_id int8 REFERENCES "Tarjetas"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS cuenta_id int8 REFERENCES "CuentasFinancieras"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS persona_id int8 REFERENCES "Personas"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS vinculo varchar(12),
  ADD COLUMN IF NOT EXISTS notificacion_original_id int8 REFERENCES "NotificacionesCorreo"(id) ON DELETE SET NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_notificaciones_correo_vinculo') THEN
    ALTER TABLE "NotificacionesCorreo"
      ADD CONSTRAINT ck_notificaciones_correo_vinculo CHECK (vinculo IS NULL OR vinculo IN ('CREADA', 'EXISTENTE', 'DUPLICADO'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_notif_owner_ultimos4 ON "NotificacionesCorreo" (owner_user_id, ultimos_4);
CREATE INDEX IF NOT EXISTS idx_notif_owner_comercio ON "NotificacionesCorreo" (owner_user_id, comercio_normalizado) WHERE comercio_normalizado IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notif_compra ON "NotificacionesCorreo" (compra_credito_generada_id) WHERE compra_credito_generada_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notif_transaccion ON "NotificacionesCorreo" (transaccion_generada_id) WHERE transaccion_generada_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_notif_owner_fecha ON "NotificacionesCorreo" (owner_user_id, fecha_correo);

-- Rellena SOLO las columnas nuevas (siempre NULL hasta ahora) con lo que el sync-batch ya guardó en datos_parseados.
-- El comercio normalizado y los vínculos los calcula la aplicación al reprocesar (necesitan reglas de texto).
UPDATE "NotificacionesCorreo"
   SET ultimos_4 = datos_parseados->>'ultimos_4'
 WHERE ultimos_4 IS NULL AND datos_parseados->>'ultimos_4' ~ '^[0-9]{4}$';

UPDATE "NotificacionesCorreo"
   SET monto_original = (datos_parseados->>'monto')::numeric
 WHERE monto_original IS NULL AND datos_parseados->>'monto' ~ '^[0-9]{1,14}(\.[0-9]{1,4})?$';

UPDATE "NotificacionesCorreo"
   SET moneda = upper(datos_parseados->>'moneda')
 WHERE moneda IS NULL AND upper(datos_parseados->>'moneda') IN ('COP', 'USD');

-- ─── C. Cobros puntuales (luz, mercado, eventos…) ───
CREATE TABLE IF NOT EXISTS "CobrosPuntuales" (
  id                  int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id       int8 NOT NULL REFERENCES "Users"(id),
  concepto            varchar NOT NULL,
  categoria           varchar NOT NULL DEFAULT 'OTRO' CHECK (categoria IN ('SERVICIO', 'MERCADO', 'EVENTO', 'OTRO')),
  fecha_gasto         date NOT NULL,
  periodo_imputacion  char(7) NOT NULL,
  monto_total         numeric(15,2) NOT NULL CHECK (monto_total > 0),
  modo_division       varchar NOT NULL DEFAULT 'IGUAL' CHECK (modo_division IN ('IGUAL', 'PORCENTAJE', 'MONTO')),
  transaccion_id      int8 REFERENCES "Transacciones"(id) ON DELETE SET NULL,
  compra_credito_id   int8 REFERENCES "ComprasCredito"(id) ON DELETE SET NULL,
  notificacion_id     int8 REFERENCES "NotificacionesCorreo"(id) ON DELETE SET NULL,
  notas               text,
  estado              varchar NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'ANULADO')),
  created_at          timestamptz DEFAULT now(),
  updated_at          timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cobros_puntuales_owner_periodo ON "CobrosPuntuales" (owner_user_id, periodo_imputacion);

CREATE TABLE IF NOT EXISTS "CobrosPuntualesPersonas" (
  id          int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cobro_id    int8 NOT NULL REFERENCES "CobrosPuntuales"(id) ON DELETE CASCADE,
  persona_id  int8 NOT NULL REFERENCES "Personas"(id),
  monto       numeric(15,2) NOT NULL CHECK (monto >= 0),
  porcentaje  numeric(8,4),
  es_propio   boolean NOT NULL DEFAULT false,
  UNIQUE (cobro_id, persona_id)
);
CREATE INDEX IF NOT EXISTS idx_cobros_puntuales_personas_persona ON "CobrosPuntualesPersonas" (persona_id);

ALTER TABLE "MovimientosDeudaPersona"
  ADD COLUMN IF NOT EXISTS cobro_puntual_id int8 REFERENCES "CobrosPuntuales"(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_mov_deuda_cobro_puntual ON "MovimientosDeudaPersona" (cobro_puntual_id) WHERE cobro_puntual_id IS NOT NULL;

-- ─── D. Enlaces de cobro y pagos reportados ───
CREATE TABLE IF NOT EXISTS "EnlacesCobroPersona" (
  id                 int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id      int8 NOT NULL REFERENCES "Users"(id),
  persona_id         int8 NOT NULL REFERENCES "Personas"(id),
  periodo            char(7) NOT NULL,
  token              varchar(64) NOT NULL UNIQUE,
  snapshot           jsonb NOT NULL,
  snapshot_at        timestamptz NOT NULL DEFAULT now(),
  mensaje            text,
  instrucciones_pago text,
  expira_at          timestamptz NOT NULL,
  revocado           boolean NOT NULL DEFAULT false,
  vistas             int4 NOT NULL DEFAULT 0,
  ultima_vista_at    timestamptz,
  created_at         timestamptz DEFAULT now(),
  updated_at         timestamptz DEFAULT now(),
  UNIQUE (owner_user_id, persona_id, periodo)
);

CREATE TABLE IF NOT EXISTS "ReportesPagoPersona" (
  id                  int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id       int8 NOT NULL REFERENCES "Users"(id),
  enlace_id           int8 REFERENCES "EnlacesCobroPersona"(id) ON DELETE SET NULL,
  persona_id          int8 NOT NULL REFERENCES "Personas"(id),
  periodo             char(7) NOT NULL,
  monto_reportado     numeric(15,2) NOT NULL CHECK (monto_reportado > 0),
  fecha_pago          date NOT NULL,
  medio               varchar,
  referencia          varchar,
  comentario          text,
  comprobante_nombre  varchar,
  comprobante_tipo    varchar,
  comprobante_tamano  int4,
  comprobante         bytea,
  estado              varchar NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
  monto_aprobado      numeric(15,2),
  motivo_rechazo      text,
  cuenta_destino_id   int8 REFERENCES "CuentasFinancieras"(id) ON DELETE SET NULL,
  transaccion_id      int8 REFERENCES "Transacciones"(id) ON DELETE SET NULL,
  movimiento_id       int8 REFERENCES "MovimientosDeudaPersona"(id) ON DELETE SET NULL,
  revisado_at         timestamptz,
  created_at          timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_reportes_pago_owner_estado ON "ReportesPagoPersona" (owner_user_id, estado);
CREATE INDEX IF NOT EXISTS idx_reportes_pago_enlace ON "ReportesPagoPersona" (enlace_id);

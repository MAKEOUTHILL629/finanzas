-- Mapa respecto a la especificación (`especificación de implementación aportes carro…`):
--   ObligacionPeriodo  → "ObligacionesMes" (ya es un periodo YYYY-MM con meta); el monto abonado, el pendiente y el
--                        saldo a favor generado se CALCULAN (no se almacenan, para que no se desfasen). Solo se
--                        guarda lo que no se puede derivar: `saldo_a_favor_aplicado`.
--   AporteDiario       → "AportesDia"          AporteDetalle → "AportesDetalle" (+ cuenta, transacción y origen).
--   CargoRecurrentePersona → "CargosRecurrentesPersona" (nueva).
--   Movimientos del sub-ledger → "MovimientosDeudaPersona" (+ referencia al recurrente y al periodo de origen).
--   Origen del movimiento: se expresa con `tipo_movimiento` (columna libre, sin CHECK) y las FK existentes.
-- =============================================================================

-- ─── Periodos del carro: saldo a favor ya aplicado (trasladado a otro mes o cruzado contra el estado de cuenta) ───
ALTER TABLE "ObligacionesMes"
  ADD COLUMN IF NOT EXISTS saldo_a_favor_aplicado numeric(15,2) NOT NULL DEFAULT 0;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_obligaciones_mes_saldo_favor_aplicado') THEN
    ALTER TABLE "ObligacionesMes"
      ADD CONSTRAINT ck_obligaciones_mes_saldo_favor_aplicado CHECK (saldo_a_favor_aplicado >= 0);
  END IF;
END $$;

-- Un solo periodo por (usuario, tipo, mes): lo exige "crear o configurar la cuota de un mes". Solo si no hay duplicados.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM "ObligacionesMes" GROUP BY owner_user_id, tipo_obligacion, periodo HAVING count(*) > 1
  ) THEN
    CREATE UNIQUE INDEX IF NOT EXISTS ux_obligaciones_mes_owner_tipo_periodo
      ON "ObligacionesMes" (owner_user_id, tipo_obligacion, periodo);
  END IF;
END $$;

-- ─── Detalle del aporte: cuenta donde entró el dinero, transacción generada y periodo de origen del saldo a favor ───
ALTER TABLE "AportesDetalle"
  ADD COLUMN IF NOT EXISTS cuenta_financiera_id int8 REFERENCES "CuentasFinancieras"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS transaccion_id int8 REFERENCES "Transacciones"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS origen_obligacion_mes_id int8 REFERENCES "ObligacionesMes"(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_aportes_detalle_transaccion ON "AportesDetalle" (transaccion_id) WHERE transaccion_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_aportes_detalle_origen ON "AportesDetalle" (origen_obligacion_mes_id) WHERE origen_obligacion_mes_id IS NOT NULL;

-- ─── Cargos / abonos recurrentes por persona (vitalicios o por X meses) ───
CREATE TABLE IF NOT EXISTS "CargosRecurrentesPersona" (
  id                 int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id      int8 NOT NULL REFERENCES "Users"(id),
  persona_id         int8 NOT NULL REFERENCES "Personas"(id),
  concepto           varchar NOT NULL,
  valor_mensual      numeric(15,2) NOT NULL CHECK (valor_mensual > 0),
  naturaleza         varchar NOT NULL DEFAULT 'CARGO_A_COBRAR'
                     CHECK (naturaleza IN ('CARGO_A_COBRAR', 'ABONO_A_FAVOR')),
  modalidad_duracion varchar NOT NULL DEFAULT 'INDEFINIDO'
                     CHECK (modalidad_duracion IN ('INDEFINIDO', 'PLAZO_FIJO')),
  numero_meses       int4 CHECK (numero_meses IS NULL OR numero_meses >= 1),
  mes_inicio         char(7) NOT NULL CHECK (mes_inicio ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  mes_fin            char(7) CHECK (mes_fin IS NULL OR mes_fin ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  cuotas_generadas   int4 NOT NULL DEFAULT 0 CHECK (cuotas_generadas >= 0),
  dia_cobro          int2 NOT NULL DEFAULT 1 CHECK (dia_cobro BETWEEN 1 AND 31),
  activo             boolean NOT NULL DEFAULT true,
  estado             varchar NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'FINALIZADO')),
  notas              text,
  created_at         timestamptz DEFAULT now(),
  updated_at         timestamptz DEFAULT now(),
  -- PLAZO_FIJO exige numero_meses y mes_fin; INDEFINIDO no los lleva
  CONSTRAINT ck_cargos_recurrentes_persona_duracion CHECK (
    (modalidad_duracion = 'PLAZO_FIJO' AND numero_meses IS NOT NULL AND mes_fin IS NOT NULL)
    OR (modalidad_duracion = 'INDEFINIDO' AND numero_meses IS NULL AND mes_fin IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_cargos_recurrentes_persona_owner ON "CargosRecurrentesPersona" (owner_user_id, persona_id, activo, estado);

-- ─── Sub-ledger: origen de los nuevos asientos (trazabilidad, idempotencia y reversión) ───
ALTER TABLE "MovimientosDeudaPersona"
  ADD COLUMN IF NOT EXISTS cargo_recurrente_persona_id int8 REFERENCES "CargosRecurrentesPersona"(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS obligacion_mes_id int8 REFERENCES "ObligacionesMes"(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_mov_deuda_cargo_recurrente
  ON "MovimientosDeudaPersona" (cargo_recurrente_persona_id) WHERE cargo_recurrente_persona_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_mov_deuda_obligacion
  ON "MovimientosDeudaPersona" (obligacion_mes_id) WHERE obligacion_mes_id IS NOT NULL;

-- Tipos de movimiento nuevos (columna libre `tipo_movimiento`, sin CHECK):
--   CARGO_RECURRENTE_PERSONA  (+1)  cargo mensual recurrente a una persona
--   ABONO_RECURRENTE_PERSONA  (-1)  descuento / valor a favor mensual recurrente
--   ABONO_SALDO_FAVOR_CARRO   (-1)  saldo a favor de la cuota del carro aplicado al estado de cuenta de fin de mes

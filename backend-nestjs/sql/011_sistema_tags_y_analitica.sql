CREATE TABLE IF NOT EXISTS "Etiquetas" (
  id               int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id    int8 NOT NULL REFERENCES "Users"(id),
  slug             varchar(80) NOT NULL,
  nombre           varchar(120) NOT NULL,
  color            varchar(30),
  icono            varchar(60),
  tipo_agrupacion  varchar(20) NOT NULL DEFAULT 'HABITO' CHECK (tipo_agrupacion IN ('COMERCIO','CATEGORIA','VIAJE','HABITO')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (owner_user_id, slug)
);

CREATE TABLE IF NOT EXISTS "ReglasAutoTag" (
  id                      int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id           int8 NOT NULL REFERENCES "Users"(id),
  patron_comercio_regex   varchar(500),
  patron_descripcion_regex varchar(500),
  monto_min               numeric(15,2),
  monto_max               numeric(15,2),
  comercio_canonico       varchar(120),
  tags_slugs              text[] NOT NULL DEFAULT '{}',
  prioridad               int4 NOT NULL DEFAULT 100,
  activo                  boolean NOT NULL DEFAULT true,
  created_at              timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_reglas_auto_tag_owner ON "ReglasAutoTag" (owner_user_id, activo, prioridad);

ALTER TABLE "ComprasCredito"
  ADD COLUMN IF NOT EXISTS tags text[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS comercio_canonico varchar(120);

ALTER TABLE "Transacciones"
  ADD COLUMN IF NOT EXISTS tags text[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS comercio_canonico varchar(120);

CREATE INDEX IF NOT EXISTS idx_compras_tags_gin ON "ComprasCredito" USING GIN (tags);
CREATE INDEX IF NOT EXISTS idx_transacciones_tags_gin ON "Transacciones" USING GIN (tags);
CREATE INDEX IF NOT EXISTS idx_compras_comercio_canonico ON "ComprasCredito" (owner_user_id, comercio_canonico);
CREATE INDEX IF NOT EXISTS idx_transacciones_comercio_canonico ON "Transacciones" (owner_user_id, comercio_canonico);
